// Find room for a whole wandering pack in the finished layout, off the main routes.
const regions = [];
const camps = R.SPAWNS.map(([type, x, y]) => ({type, x, y}));
const distance = (p, q) => Math.hypot(p.x - q.x, p.y - q.y);
for (const cluster of R.CLUSTERS.filter(c => !c.safe)) {
  const local = camps.filter(p => R.clusterOf(p) === cluster.id);
  const types = [...new Set(local.map(p => p.type))].filter(type => !R.TYPES[type].boss && !R.TYPES[type].elite);
  if (!types.length) continue;
  const radius = Math.max(...types.map(type => R.TYPES[type].radius));
  const candidates = [];
  for (let y = cluster.y + 140; y < cluster.y + cluster.h - 115; y += 42) {
    for (let x = cluster.x + 140; x < cluster.x + cluster.w - 115; x += 42) {
      const p = {x, y};
      if (R.clusterOf(p) !== cluster.id || R.inVillage(x, y) || R.inCity(x, y)) continue;
      if (!L.free(p, radius + 24) || !L.gateFree(p, 240)) continue;
      if (R.DUNGEONS.some(d => distance(p, d.entry) < 160) || distance(p, R.MONOLITH) < 150) continue;
      if (Math.abs(x - R.PASS.barrierX) < 120 && y > R.PASS.y - 100 && y < R.PASS.y + R.PASS.h + 100) continue;
      if (R.NODES.some(n => distance(p, n) < radius + 90) || local.some(m => distance(p, m) < radius + R.TYPES[m.type].radius + 45)) continue;
      if (L.roadFree(p, 85)) candidates.push(p);
    }
  }
  let seed = ((cluster.y << 16) ^ cluster.x) >>> 0;
  for (let i = candidates.length - 1; i > 0; i--) {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    const j = Math.floor((seed / 4294967296) * (i + 1));
    [candidates[i], candidates[j]] = [candidates[j], candidates[i]];
  }
  const sites = [];
  for (const p of candidates) {
    if (sites.some(site => distance(site[0], p) < 350)) continue;
    const separation = radius * 2 + 25;
    const nearby = candidates.filter(q => distance(p, q) > separation && distance(p, q) < 210 && !R.lineBlocked(p.x, p.y, q.x, q.y));
    const second = nearby[0], third = nearby.find(q => second && distance(second, q) > separation);
    if (third) sites.push([p, second, third]);
    if (sites.length === 6) break;
  }
  if (!sites.length) throw Error('No clear encounter site in ' + cluster.id);
  regions.push({cluster: cluster.id, types, sites});
}
if (!regions.length) throw Error('No eligible regions for wandering packs');
const header = '/* Generated by plan-layout.cjs from the finished beta world. */\n';
fs.writeFileSync(path.join(__dirname, 'encounter-sites.js'), header +
  '(function(root, sites){if(typeof module==="object" && module.exports) module.exports=sites; else root.HoMoWEncounterSites=sites;})(globalThis, [\n' +
  regions.map(region => JSON.stringify(region)).join(',\n') + '\n]);\n');
console.log('Planned wandering pack sites:', regions.reduce((n, r) => n + r.sites.length, 0), 'in', regions.length, 'regions');
